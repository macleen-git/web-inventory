CREATE DATABASE IF NOT EXISTS hardware_inventory_v2 CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE hardware_inventory_v2;
CREATE TABLE IF NOT EXISTS products (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product VARCHAR(150) NOT NULL UNIQUE,
 category VARCHAR(100) NOT NULL,
 buy DECIMAL(12,2) NOT NULL DEFAULT 0,
 sell DECIMAL(12,2) NOT NULL DEFAULT 0,
 stock INT UNSIGNED NOT NULL DEFAULT 0,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS stock_in (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id INT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 unit_cost DECIMAL(12,2) NOT NULL,
 total_cost DECIMAL(12,2) NOT NULL,
 date DATE NOT NULL,
 note TEXT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_stockin_product FOREIGN KEY(product_id) REFERENCES products(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 INDEX idx_stockin_date(date)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS sales (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id INT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 date DATE NOT NULL,
 amount DECIMAL(12,2) NOT NULL,
 unit_cost DECIMAL(12,2) NOT NULL,
 profit DECIMAL(12,2) NOT NULL,
 note TEXT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_sales_product FOREIGN KEY(product_id) REFERENCES products(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 INDEX idx_sales_date(date)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS damaged_items (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 product_id INT UNSIGNED NOT NULL,
 quantity INT UNSIGNED NOT NULL,
 date DATE NOT NULL,
 reason VARCHAR(255) NOT NULL DEFAULT '',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_damaged_product FOREIGN KEY(product_id) REFERENCES products(id) ON UPDATE CASCADE ON DELETE RESTRICT,
 INDEX idx_damaged_date(date)
) ENGINE=InnoDB;